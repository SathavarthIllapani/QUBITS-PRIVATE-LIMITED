/**
 * Client-side export of a reviewed run to Excel (.xlsx) or a print-ready PDF,
 * including a basic audit trail (who, when, source file, formula reference).
 * Nothing is sent to a server — the report is built in the browser.
 */
import { CALCULATORS, type CalculatorDef } from "@/lib/calculators/registry";
import type { AnalysisDTO } from "@/lib/analysis/types";

export interface ExportAnalyst {
  name: string;
  email: string;
}

export interface ReportModel {
  reportId: string;
  title: string;
  fileBase: string;
  reference: string;
  formula: string;
  audit: [string, string][];
  inputs: [string, string][];
  outputs: [string, string][];
  verdicts: { status: string; message: string }[];
}

export const REPORT_DISCLAIMER =
  "Decision support only. Verify all values against the original records and approved procedures. " +
  "This report is generated by the Qubits Lab Calculator and is not a validated GxP record unless " +
  "reviewed and approved under your quality system.";

const VERDICT_LABEL: Record<string, string> = {
  pass: "PASS",
  fail: "FAIL",
  warn: "WATCH",
  info: "INFO",
};

/** A run can be exported once it has been reviewed and saved. */
export function canExport(entry: AnalysisDTO): boolean {
  return (
    entry.status === "reviewed" &&
    !!entry.calculatorId &&
    !!entry.values &&
    !!entry.outputs &&
    CALCULATORS.some((calc) => calc.id === entry.calculatorId)
  );
}

function formatDate(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return `${date.toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" })} (${date.toISOString()})`;
}

function formatInput(def: CalculatorDef, key: string, raw: string): string {
  const field = def.fields.find((f) => f.key === key);
  if (!field) return raw;
  if (field.type === "select") {
    return field.options?.find((o) => o.value === raw)?.label ?? raw;
  }
  if (raw.trim() === "") return "—";
  return field.unit ? `${raw} ${field.unit}` : raw;
}

function formatOutput(def: CalculatorDef, key: string, raw: number | string | null): string {
  const output = def.outputs.find((o) => o.key === key);
  if (raw === null || raw === undefined) return "—";
  if (typeof raw === "number") {
    const text = Number.isFinite(raw) ? raw.toFixed(output?.decimals ?? 2) : "—";
    return output?.unit && text !== "—" ? `${text} ${output.unit}` : text;
  }
  return raw;
}

export function buildReport(entry: AnalysisDTO, analyst: ExportAnalyst): ReportModel | null {
  if (!canExport(entry)) return null;
  const def = CALCULATORS.find((calc) => calc.id === entry.calculatorId);
  if (!def || !entry.values || !entry.outputs) return null;

  const who = analyst.name ? `${analyst.name} <${analyst.email}>` : analyst.email || "Unknown";
  const stamp = new Date(entry.updatedAt).toISOString().slice(0, 10).replace(/-/g, "");

  return {
    reportId: entry.id,
    title: def.title,
    fileBase: `${def.id}_${entry.id.slice(0, 8)}_${stamp}`,
    reference: def.reference,
    formula: def.formula ?? "",
    audit: [
      ["Report ID", entry.id],
      ["Analyst", who],
      ["Source document", entry.fileName],
      ["Run created", formatDate(entry.createdAt)],
      ["Reviewed and saved", formatDate(entry.updatedAt)],
      ["Exported", formatDate(new Date().toISOString())],
      ["Status", "Reviewed by analyst"],
    ],
    inputs: def.fields.map((field) => [
      field.label,
      formatInput(def, field.key, entry.values?.[field.key] ?? ""),
    ]),
    outputs: def.outputs.map((out) => [
      out.label,
      formatOutput(def, out.key, entry.outputs?.[out.key] ?? null),
    ]),
    verdicts: (entry.verdicts ?? []).map((v) => ({
      status: VERDICT_LABEL[v.status] ?? v.status.toUpperCase(),
      message: v.message,
    })),
  };
}

/* ---------------------------------- Excel ---------------------------------- */

export async function exportRunToExcel(entry: AnalysisDTO, analyst: ExportAnalyst): Promise<boolean> {
  const report = buildReport(entry, analyst);
  if (!report) return false;

  // Loaded on demand so the large spreadsheet library is not in the main bundle.
  const mod = await import("xlsx");
  const XLSX = ((mod as unknown as { default?: typeof mod }).default ?? mod) as typeof mod;

  const rows: (string | number)[][] = [
    ["Qubits Private Limited — Lab Calculator report"],
    [report.title],
    ["Reference", report.reference],
  ];
  if (report.formula) rows.push(["Formula", report.formula]);
  rows.push([], ["AUDIT TRAIL"], ...report.audit);
  rows.push([], ["INPUTS"], ...report.inputs);
  rows.push([], ["RESULTS"], ...report.outputs);
  rows.push([], ["VERDICTS"]);
  if (report.verdicts.length === 0) rows.push(["—", "No verdicts recorded"]);
  for (const v of report.verdicts) rows.push([v.status, v.message]);
  rows.push([], ["NOTE", REPORT_DISCLAIMER]);
  rows.push([], ["Prepared by", "", "Signature", "", "Date", ""]);
  rows.push(["Reviewed by", "", "Signature", "", "Date", ""]);

  const sheet = XLSX.utils.aoa_to_sheet(rows);
  sheet["!cols"] = [{ wch: 28 }, { wch: 70 }, { wch: 12 }, { wch: 20 }, { wch: 8 }, { wch: 16 }];
  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, sheet, "Report");
  XLSX.writeFile(book, `${report.fileBase}.xlsx`);
  return true;
}

/* ----------------------------------- PDF ----------------------------------- */

export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function tableRows(rows: [string, string][]): string {
  return rows
    .map(([k, v]) => `<tr><th>${escapeHtml(k)}</th><td>${escapeHtml(v)}</td></tr>`)
    .join("");
}

export function buildReportHtml(report: ReportModel): string {
  const verdicts = report.verdicts.length
    ? report.verdicts
        .map(
          (v) =>
            `<tr><th class="v-${escapeHtml(v.status.toLowerCase())}">${escapeHtml(v.status)}</th><td>${escapeHtml(v.message)}</td></tr>`,
        )
        .join("")
    : `<tr><th>—</th><td>No verdicts recorded</td></tr>`;

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>${escapeHtml(report.fileBase)}</title>
<style>
  @page { size: A4; margin: 16mm; }
  body { font-family: -apple-system, "Segoe UI", Helvetica, Arial, sans-serif; color: #111; font-size: 12px; line-height: 1.45; }
  h1 { font-size: 18px; margin: 0 0 2px; }
  h2 { font-size: 13px; margin: 18px 0 6px; padding-bottom: 3px; border-bottom: 1px solid #999; text-transform: uppercase; letter-spacing: .04em; }
  .sub { color: #555; margin: 0 0 4px; }
  table { width: 100%; border-collapse: collapse; }
  th, td { text-align: left; vertical-align: top; padding: 4px 8px; border-bottom: 1px solid #ddd; }
  th { width: 32%; font-weight: 600; color: #333; }
  td { white-space: pre-wrap; word-break: break-word; }
  .v-fail { color: #b91c1c; } .v-pass { color: #047857; } .v-watch { color: #b45309; }
  .note { margin-top: 16px; padding: 8px 10px; border: 1px solid #ccc; background: #f6f6f6; font-size: 11px; }
  .sign { margin-top: 28px; display: flex; gap: 24px; }
  .sign div { flex: 1; border-top: 1px solid #333; padding-top: 4px; font-size: 11px; color: #333; }
</style></head><body>
<h1>Qubits Private Limited — Lab Calculator report</h1>
<p class="sub"><strong>${escapeHtml(report.title)}</strong></p>
<p class="sub">Reference: ${escapeHtml(report.reference)}${report.formula ? `<br>Formula: ${escapeHtml(report.formula)}` : ""}</p>
<h2>Audit trail</h2><table>${tableRows(report.audit)}</table>
<h2>Inputs</h2><table>${tableRows(report.inputs)}</table>
<h2>Results</h2><table>${tableRows(report.outputs)}</table>
<h2>Verdicts</h2><table>${verdicts}</table>
<div class="note">${escapeHtml(REPORT_DISCLAIMER)}</div>
<div class="sign"><div>Prepared by (name / signature / date)</div><div>Reviewed by (name / signature / date)</div></div>
</body></html>`;
}

/**
 * Opens the browser print dialog for the report; choose "Save as PDF".
 * Uses a hidden iframe so pop-up blockers are not triggered.
 */
export function printRunAsPdf(entry: AnalysisDTO, analyst: ExportAnalyst): boolean {
  const report = buildReport(entry, analyst);
  if (!report || typeof document === "undefined") return false;

  const frame = document.createElement("iframe");
  frame.setAttribute("aria-hidden", "true");
  frame.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0;";
  document.body.appendChild(frame);

  const frameDoc = frame.contentDocument;
  const frameWin = frame.contentWindow;
  if (!frameDoc || !frameWin) {
    frame.remove();
    return false;
  }

  frameDoc.open();
  frameDoc.write(buildReportHtml(report));
  frameDoc.close();

  const cleanup = () => frame.remove();
  frameWin.addEventListener("afterprint", cleanup);
  window.setTimeout(cleanup, 120_000);
  window.setTimeout(() => {
    frameWin.focus();
    frameWin.print();
  }, 250);
  return true;
}
